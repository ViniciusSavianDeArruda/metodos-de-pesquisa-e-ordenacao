    public void atualizarLista(java.util.List<String> nomes) {

    javax.swing.table.DefaultTableModel tabela =new javax.swing.table.DefaultTableModel();

    tabela.addColumn("Nº");
    tabela.addColumn("Nome");

    int numero = 1;

    for (String nome : nomes) {
        tabela.addRow(new Object[]{numero, nome});
        numero++;
    }

    tabelaResultados.setModel(tabela);
}
    
